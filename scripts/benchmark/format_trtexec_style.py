import sys
import json
from pathlib import Path


# ==========================================================
# RESULT LOCATION
#
# MODIFY when moving to another experiment / dataset / model.
# This directory must contain the provenance JSON files
# produced by benchmark_latency_trt.py.
# ==========================================================

RUNS = Path(
    "/home/zcemml1/medtronic_qat_data/runs_sanoscience"
)


# ==========================================================
# BENCHMARK IDENTIFIER
#
# MODIFY if benchmark_latency_trt.py used another SEED.
# Must match the filename generated by that benchmark.
# ==========================================================

SEED = 42


def row(label, s):
    return (
        f"{label}: "
        f"min = {s['min_ms']:.4f} ms, "
        f"max = {s['max_ms']:.4f} ms, "
        f"mean = {s['mean_ms']:.4f} ms, "
        f"median = {s['median_ms']:.4f} ms, "
        f"percentile(90%) = {s['p90_ms']:.4f} ms, "
        f"percentile(95%) = {s['p95_ms']:.4f} ms, "
        f"percentile(99%) = {s['p99_ms']:.4f} ms"
    )


def render(tag):

    # MODIFY only if the output filename convention in
    # benchmark_latency_trt.py has been changed.
    f = (
        RUNS
        / f"benchmark_latency_trt_{tag}_seed{SEED}_"
          f"pooled_summary.provenance.json"
    )

    if not f.exists():
        raise FileNotFoundError(
            f"Benchmark provenance not found: {f}"
        )

    with open(f) as file:
        d = json.load(file)

    s = d["summary"]

    n = s["Total"]["n"]
    exclusive = d["exclusive_gpu"]

    comp = s["Kernel(GPU)"]
    gpu_lat = s["GPUlatency"]

    qps_compute = (
        1000.0
        / comp["median_ms"]
    )

    print("=" * 66)
    print(
        f"  {tag.upper()} engine"
        f"  --  OUR CUDA-EVENT HARNESS "
        f"(not trtexec)"
    )

    print(
        f"  N = {n} timed inferences, "
        f"batch=1, idle-gated"
    )

    print(
        f"  exclusive_gpu = {exclusive}"
    )

    print("=" * 66)

    print(
        "=== Performance summary ==="
    )

    print(
        f"Throughput: {qps_compute:.1f} qps   "
        f"(1000 / GPU-compute median; "
        f"single stream, batch=1)"
    )

    print(
        row(
            "Latency (GPU: H2D+Compute+D2H)",
            gpu_lat,
        )
    )

    print(
        "Enqueue Time: n/a "
        "(synchronous single-shot wrapper)"
    )

    print(
        row(
            "H2D Latency",
            s["H2D(GPU)"],
        )
    )

    print(
        row(
            "GPU Compute Time",
            comp,
        )
    )

    print(
        row(
            "D2H Latency",
            s["D2H(GPU)"],
        )
    )

    walltime_median = (
        s["Total"]["median_ms"]
    )

    tag_flag = (
        ""
        if exclusive
        else
        "   [wall-clock; loaded host may inflate this]"
    )

    print(
        "Total Host Walltime "
        "(pipeline, wall-clock): "
        f"{walltime_median:.4f} ms median"
        f"{tag_flag}"
    )

    print(
        "Total GPU Compute Time "
        f"(median): "
        f"{comp['median_ms']:.4f} ms"
    )

    print()


if __name__ == "__main__":

    # MODIFY defaults when comparing another group of engines.
    #
    # Examples:
    # ["fp32", "fp16"]
    # ["fp32", "fp16", "int8"]
    # ["ptq", "qat"]
    # ["qat_batch32", "ptq_int8", "fp16"]
    DEFAULT_TAGS = [
        "fp32",
        "fp16",
    ]

    tags = (
        sys.argv[1:]
        or DEFAULT_TAGS
    )

    for tag in tags:
        render(tag)
